def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=str, required=True, help="Path to data_3.csv")
    ap.add_argument("--min_cat", type=int, default=6, help="Min count for industry/country to get its own one-hot")
    ap.add_argument("--outdir", type=str, default=".", help="Directory to write outputs (CSVs)")
    args = ap.parse_args()

    df = load_data(args.data)
    df = engineer_features(df, min_cat_count=args.min_cat)

    # 1) OLS fits
    ols_summary, fitted = fit_all_ols(df)
    key_coefs = extract_key_coefs(fitted, spec="base")

    # 2) Effect decomposition
    inc_r2 = incremental_r2_table(df)

    # 3) CV predictive Pearson r
    cv = cv_table(df)

    # save
    outdir = args.outdir
    ols_summary.to_csv(f"{outdir}/ols_summary.csv", index=False)
    key_coefs.to_csv(f"{outdir}/key_coefs_base.csv", index=False)
    inc_r2.to_csv(f"{outdir}/incremental_r2.csv", index=False)
    cv.to_csv(f"{outdir}/cv_forward_by_season.csv", index=False)

    # print concise console output
    pd.set_option("display.width", 140)
    pd.set_option("display.max_columns", 50)

    print("\n=== OLS summary (R2 etc.) ===")
    print(ols_summary)

    print("\n=== Key coefficients (base spec, robust SE) ===")
    print(key_coefs)

    print("\n=== Incremental R2 (variance contribution) ===")
    print(inc_r2)

    print("\n=== Forward CV by season (Ridge; Pearson r between y and y_hat) ===")
    print(cv)

    print("\nOutputs written to:", outdir)


if __name__ == "__main__":
    main()
